#!/usr/bin/env python3
"""publish.py -- turn a site document (+ optional SQLite db and SVG map) into DNS TXT records.

    publish.py site.txt --host example.com --out zone/ [--db site.db] [--map world.svg]
               [--chunk 1000] [--ttl 300]

Writes  zone/<host>.zone  (BIND fragment)  and  zone/<host>.json  (records as JSON, the
shape the mock resolver and registrar scripts read).  See SPEC.md, "Record layout".
"""
import argparse, base64, gzip, hashlib, json, os, sys


def blob_to_chunks(data: bytes, chunk: int):
    if not data:
        return []
    packed = base64.b64encode(gzip.compress(data, compresslevel=9, mtime=0)).decode("ascii")
    return [packed[i:i + chunk] for i in range(0, len(packed), chunk)]


def txt_strings(s: str, width: int = 255):
    """Split one chunk into the <=255-character strings a TXT record is made of."""
    return [s[i:i + width] for i in range(0, len(s), width)]


def zone_line(name: str, ttl: int, strings):
    quoted = " ".join('"%s"' % x.replace("\\", "\\\\").replace('"', '\\"') for x in strings)
    return f"{name}.\t{ttl}\tIN\tTXT\t{quoted}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("site")
    ap.add_argument("--host", required=True)
    ap.add_argument("--out", default="zone")
    ap.add_argument("--db")
    ap.add_argument("--map")
    ap.add_argument("--chunk", type=int, default=1000, help="characters per TXT record (1000 works everywhere)")
    ap.add_argument("--cloudflare", action="store_true", help="2000-character records: Cloudflare and most hosts allow it, and it halves the record count")
    ap.add_argument("--ttl", type=int, default=300)
    a = ap.parse_args()

    if a.cloudflare and a.chunk == 1000:
        a.chunk = 2000
    host = a.host.rstrip(".").lower()
    site = open(a.site, "rb").read()
    db = open(a.db, "rb").read() if a.db else b""
    svg = open(a.map, "rb").read() if a.map else b""

    blobs = {"s": blob_to_chunks(site, a.chunk), "d": blob_to_chunks(db, a.chunk), "m": blob_to_chunks(svg, a.chunk)}
    sha = hashlib.sha256(site).hexdigest()[:8]
    manifest = f"v=1 site={len(blobs['s'])} db={len(blobs['d'])} map={len(blobs['m'])} sha={sha}"

    records = [{"name": f"_dnsite.{host}", "type": "TXT", "ttl": a.ttl, "strings": [manifest]}]
    for prefix, chunks in blobs.items():
        for i, c in enumerate(chunks):
            records.append({"name": f"{prefix}{i}.{host}", "type": "TXT", "ttl": a.ttl, "strings": txt_strings(c)})

    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, host + ".zone"), "w") as f:
        f.write(f"; dnsite v1 records for {host} -- generated by publish.py\n")
        f.write(f"; point {host} at your loader with an A or CNAME record (not included here)\n")
        for r in records:
            f.write(zone_line(r["name"], r["ttl"], r["strings"]) + "\n")
    with open(os.path.join(a.out, host + ".json"), "w") as f:
        json.dump({"host": host, "manifest": manifest, "records": records}, f, indent=1)

    total_chars = sum(len(s) for r in records for s in r["strings"])
    print(f"{host}: {len(records)} TXT records, {total_chars:,} characters of TXT data")
    print(f"  site {len(site):,} B -> {len(blobs['s'])} records | db {len(db):,} B -> {len(blobs['d'])} records | map {len(svg):,} B -> {len(blobs['m'])} records")
    print(f"  manifest: {manifest}")
    print(f"  wrote {a.out}/{host}.zone and {a.out}/{host}.json")


if __name__ == "__main__":
    main()
